"""Assemble a single-file Dive from the component kit and an app file.

    python3 assemble.py APP.tsx -o dive/index.tsx [--components kpi,line,heatmap] [--extra my.tsx ...]

A Dive is one .tsx file that may import only react, recharts, d3, lucide-react and
@motherduck/react-sql-query, so the kit is copied in as source (the shadcn way).
This script concatenates kit/core.tsx, the files of the chosen components (all by
default), any --extra files (custom components) and the app, and merges their
imports into one block at the top.

Every file declares its own imports between `// @imports` and `// @imports-end`.
The app file is your Dive: it must `export default` a component and declare
REQUIRED_DATABASES. It can use everything the kit defines (THEMES, makeTheme,
ThemeCtx, Card, BlockView, MetricCard, DatePicker, ...).

Other build scripts can import this module and call assemble() directly.
"""

import argparse
import json
import pathlib
import re

HERE = pathlib.Path(__file__).parent
NAMED = re.compile(r"import\s*\{([^}]*)\}\s*from\s*'([^']+)';", re.S)
STAR = re.compile(r"import\s*\*\s*as\s+(\w+)\s+from\s*'([^']+)';")
ORDER = ["react", "@motherduck/react-sql-query", "recharts", "lucide-react", "d3"]
MARKERS = [("// @imports", "// @imports-end"), ("// @app-imports", "// @app-imports-end"), ("// @kit-imports", "// @kit-imports-end")]


def manifest():
    return json.loads((HERE / "components.json").read_text())


def split(text):
    """(imports, body) of one source file."""
    for start, end in MARKERS:
        if end in text:
            head, rest = text.split(start, 1)
            imports, body = rest.split(end, 1)
            return imports, head.rstrip() + "\n" + body
    return "", text


def files_for(components=None):
    m = manifest()
    wanted = set(components or [])
    for c in m["components"]:  # a component's `requires` brings in the components it builds on
        if c["type"] in wanted:
            wanted |= set(c.get("requires", []))
    chosen = [c for c in m["components"] if components is None or c["type"] in wanted]
    files = [m["files"]["core"]]
    if any(c["file"] == m["files"]["blocks"] for c in chosen) or components is None:
        files.append(m["files"]["blocks"])
    for c in chosen:
        if c["file"] not in files:
            files.append(c["file"])
    return [HERE / f for f in files]


def assemble(app_text, components=None, extras=(), banner=""):
    sources = [(p.name, p.read_text()) for p in files_for(components)]
    sources += [(pathlib.Path(e).name, pathlib.Path(e).read_text()) for e in extras]
    named, star, bodies = {}, {}, []
    for name, text in sources + [("app", app_text)]:
        imports, body = split(text)
        for members, module in NAMED.findall(imports):
            named.setdefault(module, set()).update(n.strip() for n in members.split(",") if n.strip())
        for alias, module in STAR.findall(imports):
            star[module] = alias
        bodies.append((name, body.strip()))
    lines = []
    for module in sorted(set(named) | set(star), key=lambda m: ORDER.index(m) if m in ORDER else 99):
        if module in star:
            lines.append(f"import * as {star[module]} from '{module}';")
        if named.get(module):
            lines.append(f"import {{ {', '.join(sorted(named[module]))} }} from '{module}';")
    out = (banner + "\n" if banner else "") + "\n".join(lines) + "\n"
    for name, body in bodies:
        out += f"\n// ===== {name} =====\n{body}\n"
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("app")
    ap.add_argument("-o", "--out", required=True)
    ap.add_argument("--components", help="comma-separated types from components.json; default all")
    ap.add_argument("--extra", nargs="*", default=[], help="custom component files, assembled after the kit")
    a = ap.parse_args()
    comps = set(a.components.split(",")) if a.components else None
    text = assemble(pathlib.Path(a.app).read_text(), comps, a.extra, banner=f"// GENERATED by dive-components/assemble.py from {a.app}. Edit the sources, then reassemble.")
    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"{out}: {len(text):,} chars, {text.count(chr(10)):,} lines")


if __name__ == "__main__":
    main()
